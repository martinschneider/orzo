#!/bin/bash

# Re-compiles Orzo's own sources with Orzo (three times: the first pass runs the javac-built
# compiler, the later ones the Orzo-built one), except for the files listed in skiplist.txt.
# This runs after the unit and before the integration tests, so that the integration tests verify
# the self-compiled compiler.
#
# Writes the metrics shown in README.md (see update_metrics.sh) to the "stats" file:
#   progress      share of the source lines compiled by Orzo (in %)
#   javac_ms      time javac takes to compile all sources
#   orzo_ms       time the (javac-built) Orzo compiler takes to compile the same sources
#   javac_bytes   size of all class files generated by javac
#   orzo_bytes    size of all class files generated by Orzo (last pass)

set -e

sources=src/main/java
stats=stats

class_bytes() {
  find "$1" -name '*.class' -printf '%s\n' | awk '{ sum += $1 } END { print sum + 0 }'
}

now_ms() {
  echo $(($(date +%s%N) / 1000000))
}

# Lines of code without comments and empty lines (only used for the progress metric)
loc() {
  perl -0777 -pe 's{/\*.*?\*/}{}gs' "$1" | sed -e 's#//.*##' -e '/^[[:space:]]*$/d' | wc -l
}

skipped() {
  grep -v -E '^#|^$' skiplist.txt || true
}

rm -f "$stats"

compile_files=()
totalLOC=0
skippedLOC=0
while read -r file; do
  lines=$(loc "$file")
  totalLOC=$((totalLOC + lines))
  if skipped | grep -qxF "$file"; then
    skippedLOC=$((skippedLOC + lines))
  else
    compile_files+=("$file")
  fi
done < <(find "$sources" -name "*.java" | sort)

total=$(find "$sources" -name "*.java" | wc -l | xargs)
progress=$(printf %0.2f "$(echo "100 * ($totalLOC - $skippedLOC) / $totalLOC" | bc -l)")
echo "Recompiling ${#compile_files[@]}/$total files with Orzo ($progress% of LOC)"

# javac baseline (compiling all sources, like the Orzo passes below)
javacSize=$(class_bytes target/classes)
javacOut=$(mktemp -d)
start=$(now_ms)
javac -nowarn -proc:none -d "$javacOut" $(find "$sources" -name "*.java")
javacTime=$(($(now_ms) - start))
rm -rf "$javacOut"

for i in {1..3}; do
  start=$(now_ms)
  java -jar target/orzo.jar "${compile_files[@]}" -d target/classes
  elapsed=$(($(now_ms) - start))
  if [ "$i" -eq 1 ]; then
    orzoTime=$elapsed
  fi
  jar cfe target/orzo.jar io.github.martinschneider.orzo.Orzo -C target/classes .
  orzoSize=$(class_bytes target/classes)
  echo "Pass #$i: ${elapsed} ms (javac: ${javacTime} ms), class files: $orzoSize bytes (javac: $javacSize bytes)"
done

{
  echo "progress=$progress"
  echo "javac_ms=$javacTime"
  echo "orzo_ms=$orzoTime"
  echo "javac_bytes=$javacSize"
  echo "orzo_bytes=$orzoSize"
} > "$stats"
